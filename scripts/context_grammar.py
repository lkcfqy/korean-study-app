def grammar_note(token,tokens,question_final=False):
    form,tag=token['form'].translate(JAMO),token['tag']
    if tag=='XSN' and form=='네':
        return '네：表示某人一家或所属群体，如 대리네（代理家）。'
    endings=[t for t in tokens if t['tag'] not in {'SF','SP','SS','SSO','SSC','SE','SO','SW'}]
    if question_final and endings and token is endings[-1] and tag=='EC' and form in {'니','냐','나','ㄴ가','은가','는가'}:
        return form+'：'+NOTES[(form,'EF')]
    if tag=='EC' and form in {'어요','아요','에요','ㅂ니다','습니다','야','네','소','ㄹ세','다지'}:
        if (form,'EF') in NOTES:return form+'：'+NOTES[(form,'EF')]
    if tag=='ETM' and form=='는':
        return '-는：将前面的动作或状态转为修饰名词的形式。'
    if (form,tag) in NOTES:return form+'：'+NOTES[(form,tag)]
    if tag in {'VCP','VCN'}:return RULES['GRAMMAR'][tag]
    if tag.startswith(('J','E')):
        return form+'：'+RULES['GRAMMAR'].get(tag,'连接前后表达。')
    if tag in {'XSN','XPN','XSV','XSA','XR','SN','SL','SH'}:
        return form+'：'+RULES['GRAMMAR'][tag]
    return ''


def number_meaning(text):
    text=text.strip('.,?!')
    digit={'영':0,'공':0,'일':1,'이':2,'삼':3,'사':4,'오':5,'육':6,'칠':7,'팔':8,'구':9}
    unit={'십':10,'백':100,'천':1000,'만':10000,'억':100000000,'조':1000000000000}
    if text and all(ch in digit or ch in unit for ch in text):
        if all(ch in digit for ch in text):
            return ''.join(str(digit[ch]) for ch in text)+'（汉字数词）'
        total=section=number=0
        for ch in text:
            if ch in digit:number=digit[ch]
            elif unit[ch]<10000:section+=(number or 1)*unit[ch];number=0
            else:total+=(section+number or 1)*unit[ch];section=number=0
        return str(total+section+number)+'（汉字数词）'
    ones={'':0,'하나':1,'한':1,'둘':2,'두':2,'셋':3,'세':3,'넷':4,'네':4,'다섯':5,'여섯':6,'일곱':7,'여덟':8,'아홉':9}
    tens={'열':10,'스물':20,'스무':20,'서른':30,'마흔':40,'쉰':50,'예순':60,'일흔':70,'여든':80,'아흔':90}
    for prefix,value in tens.items():
        if text.startswith(prefix) and text[len(prefix):] in ones:
            return str(value+ones[text[len(prefix):]])+'（固有数词）'
    if text in ones and text:return str(ones[text])+'（固有数词）'
    return None
